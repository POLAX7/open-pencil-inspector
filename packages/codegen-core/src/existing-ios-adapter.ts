import type { CodegenInput, CodegenResult } from './contracts.ts';
import { swiftTypeName } from './contracts.ts';

export function generateExistingIOSIntegration(input: CodegenInput): CodegenResult {
  const profile = input.integrationProfile;
  if (!profile) return { files: [], diagnostics: [] };
  const typeName = swiftTypeName(input.featureName);
  const entryPoints = [
    ...(profile.entryPoints.swiftUI ? [`    public static let swiftUIEntryPoint = "${profile.entryPoints.swiftUI.typeName}"`] : []),
    ...(profile.entryPoints.uikit ? [`    public static let uikitEntryPoint = "${profile.entryPoints.uikit.typeName}"`] : []),
  ].join('\n');
  const contents = `// Generated by open-pencil-inspector. Do not edit manually.
import Foundation

/// Explicit host integration metadata. The host app owns the actual coordinator and DI calls.
public enum ${typeName}ExistingAppIntegration {
    public static let projectPath = "${profile.projectPath}"
    public static let module = "${profile.module}"
    public static let feature = "${profile.feature}"
    public static let coordinatorType = "${profile.navigation.coordinatorType}"
    public static let navigationEntryMethod = "${profile.navigation.entryMethod}"
    public static let dependencyContainerType = "${profile.dependencyInjection.containerType}"
    public static let dependencyRegistrationMethod = "${profile.dependencyInjection.registrationMethod}"
    public static let assetRelativePath = "${profile.assetDestination.relativePath}"
    public static let assetBundle = "${profile.assetDestination.bundle}"
${entryPoints}
}

/// The existing app implements this boundary. Inspector does not assume its coordinator or DI signatures.
@MainActor public protocol ${typeName}ExistingAppAdapter {
    func registerDependencies()
    func present(route: ${typeName}Route, transition: ${typeName}Transition)
}
`;
  return { files: [{ path: `${typeName}ExistingAppIntegration.swift`, contents }], diagnostics: [] };
}
