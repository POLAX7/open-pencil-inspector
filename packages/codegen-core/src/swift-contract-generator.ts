import type { CodegenInput, CodegenResult } from './contracts.ts';
import { swiftCaseName, swiftTypeName } from './contracts.ts';
import { buildNavigationScaffold } from './navigation-scaffold.ts';

export function generateSwiftContracts(input: CodegenInput): CodegenResult {
  const typeName = swiftTypeName(input.featureName);
  const scaffold = input.navigationScaffold ?? buildNavigationScaffold(input.flow);
  const routes = scaffold.screens.map((screen, index) => `    case ${swiftCaseName(screen.id, `screen${index + 1}`)}`).join('\n');
  const transitions = scaffold.transitions.map((transition, index) => {
    const event = swiftCaseName(`${transition.from} to ${transition.to} ${transition.event}`, `transition${index + 1}`);
    return `    case ${event}`;
  }).join('\n');
  const transitionCases = transitions || '    case none';
  const eventCases = [...new Set(scaffold.transitions.map((transition) => `    case ${swiftCaseName(transition.event, 'transition')}`))].join('\n');
  const presentationCases = scaffold.screens.map((screen) => `    case ${swiftCaseName(screen.id, 'screen')}`).join('\n');
  const presentationValues = scaffold.screens.map((screen) => `        case .${swiftCaseName(screen.id, 'screen')}: return .${screen.presentation ?? 'root'}`).join('\n');
  const contents = `// Generated by open-pencil-inspector. Do not edit manually.
import Foundation

public enum ${typeName}Route: Hashable {
${routes || '    case root'}
}

public enum ${typeName}Presentation {
    case push
    case modal
    case sheet
    case replace
    case root
}

public enum ${typeName}RoutePresentation {
${presentationCases || '    case root'}
    public var presentation: ${typeName}Presentation {
        switch self {
${presentationValues || '        case .root: return .root'}
        }
    }
}

public enum ${typeName}Event {
    case appeared
    case retry
${eventCases}
}

public struct ${typeName}Dependencies {
    public let repository: any ${typeName}RepositoryProtocol
    public init(repository: any ${typeName}RepositoryProtocol) { self.repository = repository }
}

public protocol ${typeName}RepositoryProtocol {
    func load() async throws
}

public enum ${typeName}FeatureState {
    case idle
    case loading
    case loaded
    case empty
    case failed(message: String)
}

public typealias ${typeName}LoadState = ${typeName}FeatureState

@MainActor public protocol ${typeName}ViewModelProtocol: AnyObject {
    var state: ${typeName}FeatureState { get }
    func send(_ event: ${typeName}Event)
}
`;
  const navigation = `public enum ${typeName}Transition {
${transitionCases}
}

@MainActor public protocol ${typeName}Coordinator {
    func navigate(to route: ${typeName}Route, transition: ${typeName}Transition)
}
`;
  const noOp = `
@MainActor public final class ${typeName}NoOpCoordinator: ${typeName}Coordinator {
    public init() {}
    public func navigate(to route: ${typeName}Route, transition: ${typeName}Transition) {}
}
`;
  return { files: [{ path: `${typeName}Contracts.swift`, contents: contents + '\n' + navigation + noOp }], diagnostics: [] };
}
